export const metadata: Metadata = { title: { default: "TrustBench", template: "%s · TrustBench" }, description: "Evidence for AI reliability." };

// Set the theme before the first paint, so there is no flash.
const THEME = `try{var t=localStorage.getItem("tb-theme");if(!t)t=matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light";document.documentElement.dataset.theme=t}catch(e){}`;

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head><script dangerouslySetInnerHTML={{ __html: THEME }} /></head>
      <body>{children}</body>
    </html>
  );
}
